CREATE DATABASE IF NOT EXISTS visionbox CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE visionbox;

CREATE TABLE IF NOT EXISTS usuarios (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(80) NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE,
  senha_hash VARCHAR(255) NOT NULL,
  is_admin TINYINT(1) NOT NULL DEFAULT 0,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS titulos (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  titulo VARCHAR(120) NOT NULL,
  tipo ENUM('filme','serie','documentario','show_ao_vivo') NOT NULL,
  genero VARCHAR(40) NOT NULL,
  ano SMALLINT UNSIGNED NOT NULL,
  duracao_min SMALLINT UNSIGNED NOT NULL,
  classificacao VARCHAR(3) NOT NULL DEFAULT 'L',
  sinopse TEXT NOT NULL,
  cor1 CHAR(7) NOT NULL DEFAULT '#7A0A14',
  cor2 CHAR(7) NOT NULL DEFAULT '#141414',
  capa_url VARCHAR(255) NULL,
  banner_url VARCHAR(255) NULL,
  video_url VARCHAR(255) NULL,
  destaque TINYINT(1) NOT NULL DEFAULT 0,
  visivel TINYINT(1) NOT NULL DEFAULT 1,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_tipo (tipo)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS progresso (
  usuario_id INT UNSIGNED NOT NULL,
  titulo_id INT UNSIGNED NOT NULL,
  segundo_atual INT UNSIGNED NOT NULL DEFAULT 0,
  pct TINYINT UNSIGNED NOT NULL DEFAULT 0,
  atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (usuario_id, titulo_id),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
  FOREIGN KEY (titulo_id) REFERENCES titulos(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS favoritos (
  usuario_id INT UNSIGNED NOT NULL,
  titulo_id INT UNSIGNED NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (usuario_id, titulo_id),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
  FOREIGN KEY (titulo_id) REFERENCES titulos(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS visualizacoes (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  usuario_id INT UNSIGNED NOT NULL,
  titulo_id INT UNSIGNED NOT NULL,
  iniciada_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_usuario (usuario_id, iniciada_em),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
  FOREIGN KEY (titulo_id) REFERENCES titulos(id) ON DELETE CASCADE
) ENGINE=InnoDB;
